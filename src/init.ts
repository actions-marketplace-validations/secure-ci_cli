/** Options for the workflow that `secureci init` generates. */
export interface InitWorkflowOptions {
  /**
   * Version of the CLI generating the workflow (package.json `version`). The
   * action is pinned to its release tag, `secure-ci/cli@v<version>`.
   */
  version: string;
  /** Path to a pipeline contract to check workflows against (optional). */
  contract?: string;
  /**
   * Upload the SARIF report to GitHub code scanning. Defaults to true, which
   * also requests the `security-events: write` permission the upload needs
   * (on the job).
   */
  upload?: boolean;
}

/**
 * Render a ready-to-commit `.github/workflows/secureci.yml` that runs SecureCI
 * on every pull request via the published `secure-ci/cli` action, pinned to
 * the release tag matching this CLI's version.
 *
 * The output is deterministic for a given set of options, so it can be
 * regenerated and diffed. With uploads on (the default) the job asks for
 * `security-events: write` and lets the action upload SARIF; with uploads off
 * it keeps `contents: read` only and passes `upload-sarif: false`.
 */
export function renderInitWorkflow(options: InitWorkflowOptions): string {
  const upload = options.upload !== false;
  const contract = options.contract?.trim();

  const lines = [
    '# Validate GitHub Actions workflows with SecureCI on every pull request.',
    '# Generated by `secureci init`; edit freely.',
    'name: SecureCI',
    '',
    'on:',
    '  - pull_request',
    '',
    'permissions:',
    '  contents: read',
    '',
    'jobs:',
    '  secureci:',
    '    runs-on: ubuntu-latest'
  ];
  // Write scopes belong on the job, not the workflow. Job-level permissions
  // replace the top-level ones, so contents: read is repeated for checkout.
  if (upload) {
    lines.push(
      '    permissions:',
      '      contents: read',
      '      security-events: write'
    );
  }

  lines.push(
    '    steps:',
    '      - uses: actions/checkout@v4',
    `      - uses: secure-ci/cli@v${options.version}`
  );

  const withLines: string[] = [];
  if (contract) withLines.push(`          contract: ${yamlScalar(contract)}`);
  if (!upload) withLines.push('          upload-sarif: false');
  if (withLines.length > 0) {
    lines.push('        with:', ...withLines);
  }

  lines.push('');
  return lines.join('\n');
}

/** Quote a scalar only when YAML would otherwise misread it. */
function yamlScalar(value: string): string {
  return /^[A-Za-z0-9._/@-]+$/.test(value) ? value : JSON.stringify(value);
}
